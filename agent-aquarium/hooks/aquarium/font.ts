export const GLYPH_W = 3
export const GLYPH_H = 5
export const ADVANCE = 4

export function glyphOf(ch: string): [string, string, string, string, string] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS['?']
}

/** Width in pixels of `text` drawn at `scale`. */
export function measureText(text: string, scale = 1): number {
  if (text.length === 0) return 0
  return (text.length * ADVANCE - 1) * scale
}

/** Calls `plot(x, y)` for every lit pixel of `text` at (x0, y0), each glyph pixel `scale` wide and tall. */
export function forEachTextPixel(text: string, x0: number, y0: number, scale: number, plot: (x: number, y: number) => void): void {
  for (let i = 0; i < text.length; i++) {
    const g = glyphOf(text[i])
    const gx = x0 + i * ADVANCE * scale
    for (let r = 0; r < GLYPH_H; r++) {
      const row = g[r]
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] !== '#') continue
        for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) plot(gx + c * scale + sx, y0 + r * scale + sy)
      }
    }
  }
}
